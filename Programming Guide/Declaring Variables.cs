public class Variables
{
    static void DeclaringVariables(string[] args)
    {
        Console.WriteLine("Hello, World!");
        // You can declare variables initially by stating its data type followed by the name you want to assign it
        int variable = 0;
        string variables = null;

        // You can then refer to the variable by stating its name

        Console.WriteLine(variable + variables);

        // Do not reference its data type again only state the variables name
    }
}